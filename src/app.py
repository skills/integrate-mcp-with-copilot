def _apply_activity_filters(category: str | None = None,
                           search: str | None = None,
                           sort: str | None = None):
    filtered_activities = dict(activities)

    if category and category.lower() != "all":
        filtered_activities = {
            name: details for name, details in filtered_activities.items()
            if details.get("category", "").lower() == category.lower()
        }

    if search:
        search_term = search.lower().strip()
        filtered_activities = {
            name: details for name, details in filtered_activities.items()
            if search_term in name.lower()
            or search_term in details.get("description", "").lower()
            or search_term in details.get("category", "").lower()
            or search_term in details.get("schedule", "").lower()
        }

    if sort in (None, "name"):
        filtered_activities = dict(sorted(filtered_activities.items(), key=lambda item: item[0].lower()))
    elif sort == "time":
        filtered_activities = dict(sorted(filtered_activities.items(), key=lambda item: item[1].get("schedule", "")))
    elif sort == "availability":
        filtered_activities = dict(sorted(
            filtered_activities.items(),
            key=lambda item: item[1]["max_participants"] - len(item[1]["participants"]),
            reverse=True
        ))

    return filtered_activities


@app.get("/")
def root():
    return RedirectResponse(url="/static/index.html")


@app.get("/activities")
def get_activities(category: str | None = None,
                  search: str | None = None,
                  sort: str | None = Query(default=None, alias="sort")):
    return _apply_activity_filters(category=category, search=search, sort=sort)


@app.post("/activities/{activity_name}/signup")
def signup_for_activity(activity_name: str, email: str):
    """Sign up a student for an activity"""
    if activity_name not in activities:
        raise HTTPException(status_code=404, detail="Activity not found")

    activity = activities[activity_name]

    if email in activity["participants"]:
        raise HTTPException(
            status_code=400,
            detail="Student is already signed up"
        )

    activity["participants"].append(email)
    return {"message": f"Signed up {email} for {activity_name}"}


@app.delete("/activities/{activity_name}/unregister")
def unregister_from_activity(activity_name: str, email: str):
    """Unregister a student from an activity"""
    if activity_name not in activities:
        raise HTTPException(status_code=404, detail="Activity not found")

    activity = activities[activity_name]

    if email not in activity["participants"]:
        raise HTTPException(
            status_code=400,
            detail="Student is not signed up for this activity"
        )

    activity["participants"].remove(email)
    return {"message": f"Unregistered {email} from {activity_name}"}
